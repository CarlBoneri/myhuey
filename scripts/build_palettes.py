"""Build src/myhuey/data/palettes.json, the palette library suggested scenes choose from.

A developer tool, run by hand; the app never runs it and never goes online for palettes.

Sources:
- COLOURlovers top palettes (CC BY-NC-SA 3.0; each entry keeps its author and URL). Skipped,
  with a message, if the API refuses automated clients.
- The Met's public-domain paintings (CC0), with palettes pulled by myhuey's own theme extractor.
- Harmonies generated by myhuey (no attribution needed).

Every palette is filtered for room light and tagged; near-duplicates are dropped.

    python scripts/build_palettes.py --out src/myhuey/data/palettes.json
"""

from __future__ import annotations

import argparse
import json
import sys
import tempfile
import time
from pathlib import Path

import requests

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from myhuey.palette import extract_theme  # noqa: E402
from myhuey.palettes import clean, generate, lab, tag, usable  # noqa: E402

HEADERS = {"User-Agent": "myhuey-palette-builder"}
GAP_SECONDS = 1.0
DUPLICATE_DISTANCE = 0.02  # about one just-noticeable step; mean OKLab distance between sorted colors below which two palettes are the same
CL_TOP = "https://www.colourlovers.com/api/palettes/top"
MET = "https://collectionapi.metmuseum.org/public/collection/v1"
MET_SEARCH = "https://collectionapi.metmuseum.org/public/collection/v1.1/search"  # v1/search retired 2026-10-01
MET_PAGE = 100
MET_DEPARTMENT_PAINTINGS = 11  # European Paintings


def short_title(text: str, limit: int = 44) -> str:
    """A title cut at a word boundary, with an ellipsis when it was cut."""
    text = " ".join(str(text or "Untitled").split())
    if len(text) <= limit:
        return text
    return text[:limit].rsplit(" ", 1)[0].rstrip(",;:") + "…"


def _get(url: str, **params):
    response = requests.get(url, params=params, headers=HEADERS, timeout=30)
    response.raise_for_status()
    time.sleep(GAP_SECONDS)
    return response


def colourlovers(limit: int) -> list[dict]:
    palettes = []
    try:
        for offset in range(0, limit, 100):
            batch = _get(CL_TOP, format="json", numResults=min(100, limit - offset), resultOffset=offset).json()
            for item in batch:
                colors = ["#" + value.lower() for value in item.get("colors") or []]
                if not usable(colors):
                    continue
                palettes.append({
                    "id": f"cl-{item['id']}", "name": short_title(item.get("title")), "colors": clean(colors),
                    "source": "colourlovers",
                    "credit": {"author": str(item.get("userName") or ""), "url": str(item.get("url") or ""),
                               "license": "CC BY-NC-SA 3.0"},
                })
    except requests.RequestException as exc:
        print(f"COLOURlovers skipped: {exc}", file=sys.stderr)
    return [palette for palette in palettes if palette["credit"]["author"] and palette["credit"]["url"].startswith("http")]


def _met_ids(wanted: int) -> list[int]:
    """Object IDs of public-domain paintings with images, a page at a time."""
    ids: list[int] = []
    offset = 0
    while len(ids) < wanted:
        page = _get(MET_SEARCH, q="painting", hasImages="true", isPublicDomain="true",
                    departmentId=MET_DEPARTMENT_PAINTINGS, offset=offset, limit=MET_PAGE).json()
        found = page.get("objectIDs") or []
        ids += found
        offset += MET_PAGE
        if not found or offset >= int(page.get("total") or 0):
            break
    return ids


def met(limit: int) -> list[dict]:
    palettes = []
    try:
        ids = _met_ids(limit)  # two moods per painting, and some fail the filter
    except requests.RequestException as exc:
        print(f"The Met skipped: {exc}", file=sys.stderr)
        return palettes
    with tempfile.TemporaryDirectory() as folder:
        for object_id in ids:
            if len(palettes) >= limit:
                break
            try:
                item = _get(f"{MET}/objects/{object_id}").json()
                image_url = item.get("primaryImageSmall")
                if not item.get("isPublicDomain") or not image_url:
                    continue
                path = Path(folder) / f"{object_id}.jpg"
                path.write_bytes(_get(image_url).content)
            except requests.RequestException as exc:
                print(f"  object {object_id} skipped: {exc}", file=sys.stderr)
                continue
            for mood in ("muted", "deep"):
                try:
                    colors = [swatch["color"] for swatch in extract_theme(path, 5, mood)]
                except Exception as exc:  # a broken image is skipped, not fatal
                    print(f"  object {object_id} unreadable: {exc}", file=sys.stderr)
                    break
                if not usable(colors):
                    continue
                title = " ".join(str(item.get("title") or "Untitled").split())[:200]
                palettes.append({
                    "id": f"met-{object_id}-{mood}", "name": f"{short_title(title)} ({mood})", "colors": clean(colors), "source": "met",
                    "credit": {"title": title, "artist": str(item.get("artistDisplayName") or ""),
                               "url": str(item.get("objectURL") or ""), "license": "CC0"},
                })
            print(f"  {len(palettes)} Met palettes", file=sys.stderr)
    return [palette for palette in palettes if palette["credit"]["url"].startswith("http")]


def _signature(colors: list[str]) -> list[tuple[float, float, float]]:
    return sorted(lab(color) for color in colors)


def _same(first: list[str], second: list[str]) -> bool:
    if len(first) != len(second):
        return False
    pairs = zip(_signature(first), _signature(second))
    return sum(sum((a - b) ** 2 for a, b in zip(x, y)) ** 0.5 for x, y in pairs) / len(first) < DUPLICATE_DISTANCE


def build(limit_cl: int, limit_met: int, generated: int) -> list[dict]:
    found = colourlovers(limit_cl) + met(limit_met)
    found += [palette.to_dict() for palette in generate(0, generated)]
    kept: list[dict] = []
    for palette in found:
        if any(_same(palette["colors"], other["colors"]) for other in kept):
            continue
        palette["tags"] = tag(palette["colors"])
        kept.append(palette)
    return kept


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", required=True)
    parser.add_argument("--limit-cl", type=int, default=600)
    parser.add_argument("--limit-met", type=int, default=300)
    parser.add_argument("--generated", type=int, default=300)
    args = parser.parse_args()
    palettes = build(args.limit_cl, args.limit_met, args.generated)
    Path(args.out).write_text(json.dumps(palettes, indent=1) + "\n", encoding="utf-8")
    counts: dict[str, int] = {}
    for palette in palettes:
        counts[palette["source"]] = counts.get(palette["source"], 0) + 1
    print(f"Wrote {len(palettes)} palettes to {args.out}: {counts}")


if __name__ == "__main__":
    main()
